#ifndef INSTRUCTION_H
#define INSTRUCTION_H

#include <cstdint>


// ============================================================
// Decoded 32-bit MIPS instruction fields
// ============================================================

struct Instruction {
    uint8_t opcode = 0;
    uint8_t rs = 0;
    uint8_t rt = 0;
    uint8_t rd = 0;
    uint8_t shamt = 0;
    uint8_t funct = 0;

    uint16_t imm = 0;

    uint32_t jaddr = 0;
};


// ============================================================
// REAL MACHINE INSTRUCTIONS
// ------------------------------------------------------------
// Pseudo-instructions do NOT reach the CPU.
//
// The assembler expands pseudo-instructions into one or more
// real instructions from this enum.
// ============================================================

enum class instructionType {

    // --------------------------------------------------------
    // Arithmetic
    // --------------------------------------------------------

    ADD,
    ADDU,
    ADDI,
    ADDIU,

    SUB,
    SUBU,


    // --------------------------------------------------------
    // Logical
    // --------------------------------------------------------

    AND,
    ANDI,

    OR,
    ORI,

    XOR,
    XORI,

    NOR,


    // --------------------------------------------------------
    // Comparisons
    // --------------------------------------------------------

    SLT,
    SLTU,

    SLTI,
    SLTIU,


    // --------------------------------------------------------
    // Shifts
    // --------------------------------------------------------

    SLL,
    SRL,
    SRA,

    SLLV,
    SRLV,
    SRAV,


    // --------------------------------------------------------
    // Multiply / Divide / HI / LO
    // --------------------------------------------------------

    MULT,
    MULTU,

    DIV,
    DIVU,

    MUL,

    MFHI,
    MFLO,

    MTHI,
    MTLO,


    // --------------------------------------------------------
    // Conditional moves / bit operations
    // --------------------------------------------------------

    MOVZ,
    MOVN,

    CLZ,
    CLO,


    // --------------------------------------------------------
    // Upper immediate
    // --------------------------------------------------------

    LUI,


    // --------------------------------------------------------
    // Branches
    // --------------------------------------------------------

    BEQ,
    BNE,

    BLEZ,
    BGTZ,

    BLTZ,
    BGEZ,

    BLTZAL,
    BGEZAL,


    // --------------------------------------------------------
    // Jumps
    // --------------------------------------------------------

    J,
    JAL,

    JALR,
    JR,


    // --------------------------------------------------------
    // Loads
    // --------------------------------------------------------

    LB,
    LBU,

    LH,
    LHU,

    LW,


    // --------------------------------------------------------
    // Stores
    // --------------------------------------------------------

    SB,
    SH,
    SW,


    // --------------------------------------------------------
    // System
    // --------------------------------------------------------

    SYSCALL,
    BREAK,


    // --------------------------------------------------------
    // Unknown machine word
    // --------------------------------------------------------

    UNKNOWN
};


#endif