.data

message:
.asciiz "Ultimate MIPS Test"

number:
.word 1234

negative:
.word -77


.text

main:

# ----------------------------
# FULL 32-BIT LI
# ----------------------------

li $t0, 0x12345678

# ----------------------------
# NORMAL LI
# ----------------------------

li $t1, 10
li $t2, 20

# ----------------------------
# MOVE
# ----------------------------

move $s0, $t1

# ----------------------------
# ARITHMETIC
# ----------------------------                                                                                                                                                  
 
add  $t3, $t1, $t2
sub  $t4, $t3, $t1

addu $t5, $t1, $t2
subu $t6, $t2, $t1

# ----------------------------
# LOGICAL
# ----------------------------

and $s1, $t1, $t2
or  $s2, $t1, $t2
xor $s3, $t1, $t2
nor $s4, $t1, $t2

andi $s5, $t2, 0xF
ori  $s6, $zero, 0xFF
xori $s7, $s6, 0xF

# ----------------------------
# COMPARISONS
# ----------------------------

slt   $t7, $t1, $t2
slti  $t8, $t1, 15
sltu  $t9, $t1, $t2
sltiu $k0, $t1, 15

# ----------------------------
# SHIFTS
# ----------------------------

sll $k1, $t1, 2
srl $gp, $k1, 1
sra $sp, $k1, 2

# ----------------------------
# MEMORY
# ----------------------------

sw $t3, 200($zero)
lw $fp, 200($zero)

# ----------------------------
# BEQ
# ----------------------------

beq $t1, $t1, beq_ok

li $v1, 999

beq_ok:
li $v1, 1

# ----------------------------
# BNE
# ----------------------------

bne $t1, $t2, bne_ok

li $a1, 999

bne_ok:
li $a1, 2

# ----------------------------
# J
# ----------------------------

j jump_ok

li $a2, 999

jump_ok:
li $a2, 3

# ----------------------------
# JAL / JR
# ----------------------------

jal function

li $a3, 4

j after_function

function:
li $a3, 40
jr $ra

after_function:

# ----------------------------
# MULT / HI / LO
# ----------------------------

li $t1, 6
li $t2, 7

mult $t1, $t2

mflo $s0
mfhi $s1

# ----------------------------
# DATA LABEL / LA
# ----------------------------

la $t0, number
lw $t1, 0($t0)

# ----------------------------
# PRINT INTEGER
# ----------------------------

move $a0, $t1
li $v0, 1
syscall

# ----------------------------
# PRINT STRING
# ----------------------------

la $a0, message
li $v0, 4
syscall

# ----------------------------
# NOP
# ----------------------------

nop

# ----------------------------
# EXIT
# ----------------------------

li $v0, 10
syscall